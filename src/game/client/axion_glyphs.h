inline IGraphics::CTextureHandle s_Texture;

inline bool Begin(IGraphics *pGraphics)
{
	if(!s_Texture.IsValid())
	{
		CImageInfo Image;
		Image.m_Width = 128;
		Image.m_Height = 72;
		Image.m_Format = CImageInfo::FORMAT_RGBA;
		Image.AllocateFillZero();
		for(int Glyph = 0; Glyph < 94; ++Glyph)
			for(int Y = 0; Y < 12; ++Y)
				for(int X = 0; X < 8; ++X)
				{
					const int Offset = ((Glyph / 16 * 12 + Y) * 128 + Glyph % 16 * 8 + X) * 4;
					Image.m_pData[Offset] = Image.m_pData[Offset + 1] = Image.m_pData[Offset + 2] = 255;
					Image.m_pData[Offset + 3] = GLYPHS[Glyph][Y] & (1 << X) ? 255 : 0;
				}
		s_Texture = pGraphics->LoadTextureRawMove(Image, 0, "axion-ascii");
	}
	if(!s_Texture.IsValid())
		return false;
	pGraphics->TextureSet(s_Texture);
	pGraphics->QuadsBegin();
	return true;
}

inline unsigned Hash(unsigned Value)
{
	Value ^= Value >> 16;
	Value *= 0x7feb352dU;
	Value ^= Value >> 15;
	return Value;
}

inline void Draw(IGraphics *pGraphics, unsigned Seed, float X, float Y, float Height)
{
	const unsigned Glyph = Hash(Seed) % 94;
	const float U = (Glyph % 16) / 16.0f;
	const float V = (Glyph / 16) / 6.0f;
	pGraphics->QuadsSetSubset(U, V, U + 1.0f / 16, V + 1.0f / 6);
	const IGraphics::CQuadItem Quad(X, Y, Height * (8.0f / 12), Height);
	pGraphics->QuadsDrawTL(&Quad, 1);
}

inline void End(IGraphics *pGraphics)
{
	pGraphics->QuadsEnd();
	pGraphics->SetColor(1, 1, 1, 1);
}
